pub fn line_height() -> i32 {
    CELL_H
}

pub fn put_pixel(fb: &mut [u8], stride: i32, w: i32, h: i32, x: i32, y: i32, color: u32) {
    if x < 0 || y < 0 || x >= w || y >= h {
        return;
    }
    let i = (y * stride + x * 4) as usize;
    if i + 4 <= fb.len() {
        fb[i..i + 4].copy_from_slice(&color.to_le_bytes());
    }
}

pub fn fill_rect(
    fb: &mut [u8],
    stride: i32,
    w: i32,
    h: i32,
    x0: i32,
    y0: i32,
    rw: i32,
    rh: i32,
    color: u32,
) {
    for y in y0..(y0 + rh) {
        for x in x0..(x0 + rw) {
            put_pixel(fb, stride, w, h, x, y, color);
        }
    }
}

pub fn stroke_rect(
    fb: &mut [u8],
    stride: i32,
    w: i32,
    h: i32,
    x0: i32,
    y0: i32,
    rw: i32,
    rh: i32,
    color: u32,
) {
    for x in x0..(x0 + rw) {
        put_pixel(fb, stride, w, h, x, y0, color);
        put_pixel(fb, stride, w, h, x, y0 + rh - 1, color);
    }
    for y in y0..(y0 + rh) {
        put_pixel(fb, stride, w, h, x0, y, color);
        put_pixel(fb, stride, w, h, x0 + rw - 1, y, color);
    }
}

pub fn draw_text(
    fb: &mut [u8],
    stride: i32,
    w: i32,
    h: i32,
    mut x: i32,
    y: i32,
    text: &str,
    color: u32,
) {
    for ch in text.chars() {
        if ch == '\n' {
            continue;
        }
        let idx = (ch as u8).saturating_sub(32) as usize;
        if idx < GLYPHS.len() {
            let g = &GLYPHS[idx];
            for row in 0..GLYPH_H {
                let bits = g[row as usize];
                for col in 0..GLYPH_W {
                    if bits & (1 << (4 - col)) != 0 {
                        put_pixel(fb, stride, w, h, x + col, y + row, color);
                    }
                }
            }
        }
        x += CELL_W;
    }
}
